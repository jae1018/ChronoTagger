def test_generated_source_is_pure_ascii():
    """Cp1252 consoles are the reason this package is ASCII-only, and a
    column name is user data: a Greek mu in a header must not put a
    non-ASCII byte in the emitted file."""
    text = generate_driver(
        vertical_stack_config(["B_perp", "n_e"]),
        data_path="/data/x.csv", fmt="csv", time_column="epoch",
        autosave_folder="./out")
    assert text.isascii()

    exotic = generate_driver(
        vertical_stack_config(["B\u00b5", "n\u03bc"]),
        data_path="/data/x.csv", fmt="csv", time_column="epoch",
        autosave_folder="./out")
    assert exotic.isascii()

    # ...and the escaped literals still name the real columns: run the
    # emitted plot_fn against a frame that HAS them.  A vacuous
    # substring check would pass on an emitter that dropped the column
    # entirely (Pack 6 recheck FINDING 3, the same trap).
    from matplotlib.figure import Figure

    ns: dict = {}
    exec(compile(exotic.split('if __name__')[0], "<driver>", "exec"), ns)
    idx = pd.date_range("2021-01-01", periods=5, freq="1min")
    frame = pd.DataFrame({"B\u00b5": np.arange(5.0),
                          "n\u03bc": np.arange(5.0)}, index=idx)
    fig = Figure()
    axs = {"panel_1": fig.add_subplot(2, 1, 1),
           "panel_2": fig.add_subplot(2, 1, 2)}
    ns["plot_fn"](axs, frame, idx[0], idx[-1])
    assert len(axs["panel_1"].lines) == 1
    assert axs["panel_1"].get_ylabel() == "B\u00b5"


def test_a_non_ascii_timedelta_unit_still_returns_ascii_text():
    """v2 / V1 MINOR-1.  `_timedelta_lit` used to interpolate the
    caller's string straight into `pd.Timedelta("%s")`, so a MICRO SIGN
    -- a unit pandas accepts -- came back in the RETURN VALUE and only
    write_driver's ascii encoder caught it.  A Pack 8 caller writing the
    text through its own utf-8 handle would have shipped it."""
    micro = "1\u00b5s"
    assert pd.Timedelta(micro) == pd.Timedelta("1us")

    text = generate_driver(
        vertical_stack_config(["BX"]),
        data_path="/d/x.csv", fmt="csv", time_column="t",
        autosave_folder="./out", window=micro, step=micro)
    assert text.isascii()
    assert "pd.Timedelta('1\\xb5s')" in text

    # ...and the escape still parses back to the same duration.
    ns: dict = {}
    exec("import pandas as pd\nw = pd.Timedelta('1\\xb5s')", ns)
    assert ns["w"] == pd.Timedelta("1us")


