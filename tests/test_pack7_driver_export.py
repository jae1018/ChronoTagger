def _norm(text: str) -> str:
    """Normalised view of generated source.

    Line endings are unified and trailing spaces dropped, so a golden
    cannot flake on invisible whitespace; everything a reader can SEE is
    still compared exactly.
    """
    unified = text.replace("\r\n", "\n").replace("\r", "\n")
    return "\n".join(line.rstrip() for line in unified.split("\n")).strip()


