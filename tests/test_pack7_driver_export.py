def _epoch_column(index, unit):
    """A genuine integer epoch in `unit`, whatever pandas' own index
    resolution happens to be.

    Under pandas 3 `pd.date_range(...)` is `datetime64[us]`, so
    `index.view("int64")` is a MICROSECOND count -- which is exactly how
    v1's fixture came to be a microsecond epoch that its driver then
    read as nanoseconds.  Convert explicitly instead of viewing.
    """
    ns = index.astype("datetime64[ns]").astype("int64")
    divisor = {"ns": 1, "us": 1000, "ms": 1000000, "s": 1000000000}[unit]
    assert (ns % divisor == 0).all(), "fixture is not exact in %s" % unit
    return ns // divisor


