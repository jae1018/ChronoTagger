def test_an_emitted_driver_survives_a_YOURS_hook_that_drops_a_column(tmp_path):
    """MAJOR-3, end to end and in a subprocess.

    The generated [YOURS] pre-launch hook demonstrates a `df.drop`. Do
    exactly that to a PLOTTED column and the driver must still start,
    with one panel showing the runtime generator's own red notice.
    """
    frame = _sample_frame()
    data = tmp_path / "sample.csv"
    frame.reset_index(names="t").to_csv(data, index=False)

    text = generate_driver(
        vertical_stack_config(["BX", "n_linear"]),
        data_path=str(data), fmt="csv", time_column="t",
        window="10min", step="5min",
        autosave_folder=str(tmp_path / "autosave"),
        source_name="dropped")
    # play the user: drop a plotted column in the pre-launch hook
    hooked = text.replace(
        "    df = load_dataframe()\n",
        '    df = load_dataframe()\n    df = df.drop(columns=["n_linear"])\n',
        1)
    assert 'df.drop(columns=["n_linear"])' in hooked

    got = _run_driver(tmp_path, hooked, "drive_dropped.py")
    assert got["rows"] == 240
    assert "n_linear" not in got["columns"]
    # panel_1 still drew its line; panel_2 drew a notice instead
    assert got["artists"]["panel_1"] == [1, 0]
    assert got["artists"]["panel_2"] == [0, 0]
    assert got["texts"]["panel_2"] == ["Error: Column 'n_linear' not found"]
